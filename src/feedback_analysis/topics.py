TOPIC_KEYWORDS = {
    "приёмная комиссия": ["приемн", "абитуриент", "поступлен", "заявлен", "документ"],
    "учебный процесс": ["занят", "лекци", "расписан", "преподават", "экзамен", "зачет"],
    "LMS / платформа": ["lms", "платформ", "сайт", "личн", "кабинет", "приложен"],
    "оплата": ["оплат", "стоимост", "платеж", "квитанц", "цена"],
    "общежитие": ["общежит", "проживан", "комнат"],
    "деканат": ["деканат", "куратор", "методист", "справк"],
    "IT-поддержка": ["поддержк", "техподдержк", "не работает", "ошибк", "сбо"],
}


def detect_topic(text: str) -> str:
    text_lower = (text or "").lower()
    best_topic, best_hits = "прочее", 0
    for topic, kws in TOPIC_KEYWORDS.items():
        hits = sum(1 for kw in kws if kw in text_lower)
        if hits > best_hits:
            best_topic, best_hits = topic, hits
    return best_topic